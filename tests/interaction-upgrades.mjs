import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-angle=swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
const state=()=>page.evaluate(()=>window.worldDiagnostics.state());
const project=(x,y,z)=>page.evaluate(([x,y,z])=>window.worldDiagnostics.project(x,y,z),[x,y,z]);
try {
  await page.route('**/assets/building-*/**', async route => { await new Promise(r=>setTimeout(r,800)); await route.continue(); });
  await page.goto('http://127.0.0.1:5173');
  await page.getByText('正在准备小镇素材…',{exact:true}).waitFor();
  assert.equal(await page.locator('canvas').count(),0,'no legacy scene during texture loading');
  await page.waitForFunction(()=>window.worldDiagnostics);
  await page.unroute('**/assets/building-*/**');
  await page.waitForTimeout(1200);
  await page.getByRole('button',{name:'暂停游戏',exact:true}).click();
  let b=(await state()).b.buildings.find(b=>b.type==='house');
  const start=await project(b.x,.65,b.z);
  const groundStart=await project(b.x,.045,b.z), groundEnd=await project(b.x+1,.045,b.z);
  const camera=await page.evaluate(()=>window.worldDiagnostics.camera());
  await page.mouse.move(start.x,start.y); await page.mouse.down(); await page.waitForTimeout(650);
  assert.equal((await state()).ui.moving,b.id,'long press enters relocation');
  await page.mouse.move(start.x+groundEnd.x-groundStart.x,start.y+groundEnd.y-groundStart.y,{steps:10});
  await page.mouse.up(); await page.waitForTimeout(500);
  const moved=(await state()).b.buildings.find(v=>v.id===b.id);
  assert.equal(moved.x,b.x+1); assert.equal(moved.z,b.z);
  assert.equal((await state()).ui.panel,null,'release does not open detail');
  assert.equal((await state()).ui.moving,null);
  assert.deepEqual(await page.evaluate(()=>window.worldDiagnostics.camera()),camera,'drag does not pan camera');
  // Invalid drop on the warehouse cannot overwrite either structure.
  const warehouse=(await state()).b.buildings.find(v=>v.type==='warehouse');
  const next=await project(moved.x,.65,moved.z), a=await project(moved.x,.045,moved.z), dest=await project(warehouse.x,.045,warehouse.z);
  await page.mouse.move(next.x,next.y);await page.mouse.down();await page.waitForTimeout(650);
  await page.mouse.move(next.x+dest.x-a.x,next.y+dest.y-a.y,{steps:10});await page.mouse.up();await page.waitForTimeout(450);
  assert.equal((await state()).b.buildings.find(v=>v.id===b.id).x,moved.x);
  assert.equal((await state()).ui.draggingBuilding,false);
  await page.evaluate(async()=>{ const url=performance.getEntriesByType('resource').map(e=>e.name).find(url=>new URL(url).pathname==='/src/stores/index.ts'); const s=await import(url); s.useResourceStore.setState({currency:10000}); s.useUIStore.setState({placement:'expand',expand:null,panel:null}); });
  const tiles=(await state()).w.tiles.overworld.length;
  await page.waitForTimeout(500);
  for(const [x,z] of [[2,0],[2,1]]) {const p=await project(x*3,.075,z*3);await page.mouse.click(p.x,p.y);await page.waitForTimeout(150);}
  await page.screenshot({path:'test-results/expansion-selection.png'});
  assert.equal((await state()).ui.expand?.length,2);
  const toggle=await project(6,.075,3);
  await page.mouse.click(toggle.x,toggle.y);await page.waitForTimeout(100);
  assert.equal((await state()).ui.expand.length,1,'click again deselects a tile');
  await page.mouse.click(toggle.x,toggle.y);await page.waitForTimeout(100);
  await page.evaluate(async()=>{const url=performance.getEntriesByType('resource').map(e=>e.name).find(url=>new URL(url).pathname==='/src/stores/index.ts');(await import(url)).useResourceStore.setState({currency:600});});
  assert.equal(await page.getByRole('button',{name:'确认扩建 2 块',exact:true}).isDisabled(),true);
  assert.equal((await state()).w.tiles.overworld.length,tiles,'insufficient funds leave all land unchanged');
  await page.evaluate(async()=>{const url=performance.getEntriesByType('resource').map(e=>e.name).find(url=>new URL(url).pathname==='/src/stores/index.ts');(await import(url)).useResourceStore.setState({currency:10000});});
  assert.match(await page.locator('.build-toolbar').innerText(),/648/);
  await page.getByRole('button',{name:'确认扩建 2 块',exact:true}).click();
  assert.equal((await state()).w.tiles.overworld.length,tiles+2);
  assert.equal((await state()).r.currency,10000-648);
  await page.getByRole('button',{name:'保存世界',exact:true}).click();
  await page.reload();await page.waitForFunction(()=>window.worldDiagnostics);await page.waitForTimeout(800);
  assert.equal((await state()).w.tiles.overworld.length,tiles+2);
  assert.equal((await state()).b.buildings.find(v=>v.id===b.id).x,moved.x);
  assert.deepEqual(errors,[]);
  await page.screenshot({path:'test-results/interaction-upgrades.png'});
  console.log('PASS loading gate, long-press drag, fixed camera, invalid drop, multi-expansion pricing and persistence');
} finally {await browser.close();}
